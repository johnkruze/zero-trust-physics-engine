//! Thermodynamic records of the gases a carbon wall can hold in a stream of
//! oxygen, nitrogen and argon with a decomposition gas of carbon, hydrogen
//! and oxygen, and of graphite. Locked data: copied number for number from
//! NASA's thermodynamic coefficient file `thermo.inp`, the database of the
//! CEA code (github.com/nasa/cea, `data/thermo.inp`, commit
//! 2f79a647e85737742fb08a127da00d1ea1d069da, SHA-256
//! `fa7746572952d74e249e818a82a35c113829742fb421a308e167185528884363`;
//! Apache License, Version 2.0; the form is NASA TP-2002-211556, McBride,
//! Zehe and Gordon). The copy read is
//! `evidence/research/heatshield_surface_model/raw/nasa_cea/thermo.inp`.
//!
//! Each record holds, for each temperature interval, seven coefficients
//! `a1..a7` and two constants `b1`, `b2`:
//!
//! ```text
//! H/RT = −a1/T² + a2 ln(T)/T + a3 + a4 T/2 + a5 T²/3 + a6 T³/4 + a7 T⁴/5 + b1/T
//! S/R  = −a1/(2T²) − a2/T + a3 ln(T) + a4 T + a5 T²/2 + a6 T³/3 + a7 T⁴/4 + b2
//! ```
//!
//! at the standard pressure of 1 bar. The enthalpy includes the heat of
//! formation at 298.15 K: the elements in their reference states have zero.
//!
//! The 52 gases are the 25 of the published TACOT surface table (PATO 3.1,
//! `tacot26.xml`) and 27 more oxygen-bearing and radical species; the list
//! and its order are those of the surface work
//! (`evidence/research/heatshield_surface_model/analysis/equil.py`, `WIDE`).
//! This file was written by a script from that reader and is not edited by
//! hand.

/// One temperature interval of a record.
pub(crate) struct Interval {
    /// The interval holds up to this temperature, kelvin. Below the first
    /// interval the first is used; above the last, the last.
    pub highest_k: f64,
    pub a: [f64; 7],
    pub b1: f64,
    pub b2: f64,
}

/// One species.
pub(crate) struct Species {
    /// Its name in `thermo.inp`.
    pub name: &'static str,
    /// Atoms of carbon, hydrogen, oxygen, nitrogen and argon in one molecule.
    pub atoms: [f64; 5],
    /// Molar mass as the file gives it, g/mol.
    pub molar_mass_g_per_mol: f64,
    /// Lowest temperature of the first interval, kelvin.
    pub lowest_k: f64,
    pub intervals: &'static [Interval],
}

